"""
Docstring for Functions.LambdaFunction

A lambda function is a small anonymous function.

A lambda function can take any number of arguments, but can only have one expression.
"""

add = lambda a : a + 10
print(add(2))

sub = lambda a, b  : a-b
print(sub(1, 2))

mul = lambda a, b, c : a*b*c
print(mul(1, 2, 4))

div = lambda a, b : a/b
print(div(4, 2))